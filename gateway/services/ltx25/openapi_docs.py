from __future__ import annotations

GENERATE_VIDEO = """
Text-to-video, or image-to-video if you attach one or more `images`, on LTX-2.5.

**Two recipes, chosen by `mode`:**
- `"fast"` (default) -- the distilled pipeline: a fixed 8-step schedule with no guidance.
  Fastest and cheapest.
- `"quality"` -- the DFR (Diffusion Fidelity Rendering) pipeline: the same distilled
  transformer, plus extra generated keyframes at half resolution and a second-stage
  detailing pass at full resolution. Sharper detail than `"fast"`; slower, and needs more
  GPU memory.

There is no `negative_prompt` field: both LTX-2.5 recipes run without guidance, so there is
nothing for one to act on.

**Clip length.** Use `duration_seconds` or `num_frames` as usual (default ~5s), or set
`auto_duration: true` to let the model predict the length from the prompt (clamped to
1-20 seconds). `auto_duration` cannot be combined with `duration_seconds` or `num_frames`.

**Multi-shot.** LTX-2.5 can cut between 2-4 shots inside one clip, holding the same
character, lighting, and voice across the cuts. There is no parameter for it -- you write the
cuts into the `prompt` in prose. See `GET /v1/guide` for how.

Output: MP4, H.264 video + AAC audio, muxed together. Video and audio are generated
*jointly* by the same model -- quoted dialogue in the prompt comes out lip-synced.

`images[].frame_idx == 0` makes that image the literal first frame (true image-to-video);
`frame_idx > 0` uses it as keyframe guidance partway through instead.
"""

INTERPOLATE = """
Generates a video that starts on `first_frame_asset_id` and ends on `last_frame_asset_id`,
with `prompt` describing the motion that connects them -- first/last-frame interpolation on
LTX-2.5. Upload both images first with `POST /v1/uploads`.

**Two recipes, chosen by `mode`**, with the same meaning as on
`POST /v1/ltx25/videos/generate`: `"fast"` (default, the distilled pipeline) and `"quality"`
(the DFR pipeline: sharper detail, slower, more GPU memory). There is no `negative_prompt`.

**How the frames are used.** The first image is placed at frame 0 and becomes the literal first
frame of the video. The last image is placed at the final frame and guides the video's ending, so
the clip lands on it. The video's length comes from `duration_seconds` or `num_frames` (default
~5s); a longer clip gives the model more time to travel between the two frames.

**Choosing the two frames.** Interpolation works best when both frames come from the same scene
(same place, subject, and lighting) and the change between them is a plausible movement or
action. When the two frames are completely different compositions (for example, a wide shot of a
courtyard and a close-up of a person), the model cannot invent a physical camera move between
them and tends to produce a cross-dissolve -- a ghosted blend of the two images -- in the middle
of the clip. It still starts and ends exactly on your frames either way.

**Image shape.** Both images are resized and center-cropped to the output size, so give them the
same aspect ratio as the output (16:9 for `landscape`, 9:16 for `portrait`) to avoid unwanted
cropping. There is no `auto_duration` on this endpoint: the last frame's position depends on
knowing the length up front.

Output: MP4, H.264 video + AAC audio, muxed together. Audio is generated by the model to match
the motion; it is not carried over from the images (which have none).
"""

AUDIO_TO_VIDEO = """
Generates video conditioned on a given audio track on LTX-2.5 -- typically speech, for
lip-synced video from a pre-recorded voice line. Upload the audio (or a video whose audio track
you want) first with `POST /v1/uploads`.

**One recipe, no `mode`.** This runs LTX-2.5's guided two-stage audio-to-video pipeline: the
full (dev) transformer at half resolution with CFG guidance, then a 2x upscale refined with the
distilled LoRA. The fast (distilled) and quality (DFR) pipelines have no audio input. Because
this recipe is guided, `negative_prompt` is honored here, unlike on the other LTX-2.5 endpoints.

The input audio is **not regenerated**: it is decoded from `audio_asset_id` (mono is converted
to stereo first) and muxed into the output unchanged; only the video is generated to match it.

**Clip length -- pick one of two ways:**
- *Fixed length* (default): `duration_seconds` or `num_frames` (default ~5s). Audio is read from
  `audio_start_time` for exactly that long.
- *Match audio*: set `audio_max_duration` (up to 20s) and leave `duration_seconds`/`num_frames`
  out. The video is as long as the audio actually read from `audio_start_time` -- at most
  `audio_max_duration`, shorter if the file ends first -- snapped to the nearest valid frame
  count.

Setting `audio_max_duration` together with `duration_seconds` or `num_frames` is rejected (422).

**Optional lip sync (`lip_sync: true`).** This pipeline follows the audio only loosely, so the speaker's
mouth does not always move properly. With `lip_sync: true`, after the video is generated a dedicated
lip-sync model (TBDub) redraws the mouth to match your audio exactly -- in the same job, on the same GPU,
with no second upload or request. Choose the LTX version first (this endpoint or its sibling); lip sync is
applied on top of it. What to know:
- `frame_rate` is forced to 25 (the rate the lip-sync model works at); an explicit `num_frames` is turned
  into the same duration and re-rounded at 25 fps. The stored request shows the values actually used.
- It adds several minutes to the job. If lip sync fails (e.g. no face could be tracked) the job still
  **succeeds** and returns the video **without** lip sync: check `lip_sync.applied` and `lip_sync.error` on
  the job, then retry only the sync with `POST /v1/tbdub/videos/lip-sync` and this job's id as
  `source_job_id`. The un-synced video stays in the job until it is deleted.
- Only the mouth, jaw and the skin around them are redrawn: eyebrows, laughter, nods and other reactions
  must be described in `prompt`. One speaker with a visible face is expected.

Output: MP4, H.264 video + the original audio muxed in unchanged.
"""

RETAKE = """
Regenerates only the `[start_time, end_time]` window of an existing video on LTX-2.5.
Both video and audio inside the window are regenerated together, driven by `prompt`; the rest
of the video is left visually the same. The whole clip is re-encoded, so frames outside the
window are very close to the source but not bit-for-bit identical.

**Distilled checkpoint only** -- the only variant the underlying pipeline ships.

**The source video must already satisfy the model's own shape constraints.** This is not
checked by this API -- a video that doesn't will fail only once the job is already running on
a GPU: frame count must be `8k+1` (97, 121, 193, ...) and width/height must each be a multiple
of 32. A video produced by `POST /v1/ltx25/videos/generate` already satisfies this.

There are no `height`/`width`/`num_frames`/`orientation` fields on this endpoint: the output
always matches the source video's resolution, frame count, and frame rate exactly.
"""

